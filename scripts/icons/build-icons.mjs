// Bundles the Lucide icons Asteria uses into frontend/src/lib/icons.ts.
//
//   node scripts/icons/build-icons.mjs [path/to/lucide-static/package]
//
// Without a path it downloads lucide-static@VERSION with `npm pack` into
// scripts/icons/.cache. Only icons named by a skill (skills/core/**/icon),
// a family default, the UI, or the EXTRA list below are bundled; skills
// written by users may use any of them (see skills/README.md).
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync, copyFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const VERSION = '1.72.0'
const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..', '..')

export const familyIcons = {
  convert: 'arrow-left-right', transform: 'scaling', sizes: 'ratio', compress: 'fold-vertical',
  adjust: 'palette', filter: 'blend', compose: 'layers', info: 'info', pdf: 'file-text',
  media: 'clapperboard', archive: 'archive', data: 'braces', meta: 'settings-2',
  document: 'file-type', ebook: 'book-open', text: 'text', subtitles: 'captions', email: 'mail',
  camera: 'aperture', vector: 'pen-tool', fonts: 'type', lut: 'swatch-book', maps: 'map', '3d': 'box',
}
// Common pictograms available to user-written skills.
const EXTRA = [
  'file', 'file-image', 'file-video', 'file-audio', 'file-code', 'file-spreadsheet', 'file-json', 'file-archive',
  'folder', 'image', 'images', 'video', 'music', 'mic', 'camera', 'type', 'text', 'code', 'terminal', 'globe',
  'link', 'mail', 'printer', 'download', 'upload', 'share', 'lock', 'unlock', 'shield', 'eye', 'eye-off', 'search',
  'calendar', 'clock', 'map-pin', 'tag', 'hash', 'list', 'table', 'chart-bar', 'scissors', 'paintbrush', 'pen',
  'square', 'circle', 'triangle', 'hexagon', 'heart', 'bookmark', 'flag', 'package', 'box', 'trash-2', 'copy',
]

function lucideDir(arg) {
  if (arg) return arg
  const cache = join(here, '.cache')
  const dir = join(cache, 'package')
  if (!existsSync(join(dir, 'icons'))) {
    mkdirSync(cache, { recursive: true })
    execFileSync('npm', ['pack', `lucide-static@${VERSION}`, '--silent'], { cwd: cache })
    execFileSync('tar', ['xzf', `lucide-static-${VERSION}.tgz`], { cwd: cache })
  }
  return dir
}

const walk = (d) => readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : n.endsWith('.json') ? [join(d, n)] : []))

const src = lucideDir(process.argv[2])
const names = new Set([...Object.values(familyIcons), ...EXTRA])
for (const f of walk(join(root, 'skills', 'core'))) {
  const icon = JSON.parse(readFileSync(f, 'utf8')).icon
  if (icon) names.add(icon)
}
const forbidden = /(^|-)(sparkles?|stars?|wand|magic|bot|brain|message[a-z-]*)(-|$)/
const out = {}
for (const n of [...names].sort()) {
  if (forbidden.test(n)) throw new Error(`icon ${n} is not allowed`)
  const file = join(src, 'icons', `${n}.svg`)
  if (!existsSync(file)) throw new Error(`unknown Lucide icon ${n}`)
  const svg = readFileSync(file, 'utf8')
  const inner = svg
    .slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'))
    .replace(/\s*\n\s*/g, '')
    .trim()
  out[n] = inner
}
const ts = `// Generated by scripts/icons/build-icons.mjs from Lucide ${VERSION} (ISC,
// see assets/icons/LICENSE-lucide.txt). Do not edit by hand.

/** Inner SVG markup (24x24 viewBox, stroke-based) by Lucide icon name. */
export const icons: Record<string, string> = ${JSON.stringify(out, null, 2)}

/** Icon shown for a skill without its own (or with an unknown one). */
export const familyIcons: Record<string, string> = ${JSON.stringify(familyIcons, null, 2)}
`
writeFileSync(join(root, 'frontend', 'src', 'lib', 'icons.ts'), ts)
mkdirSync(join(root, 'frontend', 'src', 'assets', 'icons'), { recursive: true })
copyFileSync(join(src, 'LICENSE'), join(root, 'frontend', 'src', 'assets', 'icons', 'LICENSE-lucide.txt'))
console.log(`${Object.keys(out).length} icons -> frontend/src/lib/icons.ts`)
