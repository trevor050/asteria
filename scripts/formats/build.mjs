#!/usr/bin/env node
// Builds docs/formats.json and the README's format list from the format
// matrix (internal/engine/matrix_test.go). Every conversion listed was run on
// a real fixture and its output checked by an independent tool on at least
// one platform; nothing else feeds these numbers.
//
// 1. Run the matrix on each platform, writing a raw report:
//      ASTERIA_MATRIX=1 ASTERIA_MATRIX_OUT=docs/matrix/linux-amd64.json go test ./internal/engine -run TestMatrix
// 2. node scripts/formats/build.mjs            merges docs/matrix/*.json into docs/formats.json
//                                              and rewrites README.md between its markers
//    node scripts/formats/build.mjs --check    fails if either is out of date
//
// README markers: <!-- formats:count -->N<!-- /formats:count -->,
// <!-- formats:builtin -->N<!-- /formats:builtin -->,
// <!-- formats:pairs -->N<!-- /formats:pairs --> and the block between
// <!-- formats:start --> and <!-- formats:end -->.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { nameOf } from './names.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const matrixDir = join(root, 'docs', 'matrix')
const manifest = JSON.parse(readFileSync(join(root, 'addons', 'manifest.json'), 'utf8'))
const check = process.argv.includes('--check')

// Families as people think of them; categories map onto them.
const familyOf = {
  convert: 'Images', transform: 'Images', compress: 'Images', adjust: 'Images', filter: 'Images',
  compose: 'Images', sizes: 'Images', info: 'Images', camera: 'Camera RAW and rare images', vector: 'Vector',
  lut: 'Color LUTs', pdf: 'PDF', document: 'Documents', ebook: 'Ebooks', media: 'Audio and video',
  subtitles: 'Subtitles', data: 'Data and config', text: 'Text and encoding', email: 'Email', fonts: 'Fonts',
  maps: 'Maps and GPS', '3d': '3D models', archive: 'Archives',
}
const familyOrder = [...new Set(Object.values(familyOf))]

const engineFor = (tool) => manifest.engines.find((e) => e.tools.includes(tool))
const bare = (ext) => (ext === 'folder' || ext === '*' ? ext : ext.replace(/^\./, '').toLowerCase())

// ---- merge ---------------------------------------------------------------
const raws = readdirSync(matrixDir).filter((f) => f.endsWith('.json')).sort()
const platforms = {}
const byKey = new Map()
for (const file of raws) {
  const r = JSON.parse(readFileSync(join(matrixDir, file), 'utf8'))
  const plat = r.platform.replace('/', '-')
  platforms[plat] = { tested: r.generated, engines: r.engines ?? {} }
  for (const c of r.conversions) {
    const key = `${c.from}>${c.to}>${c.skill}`
    let row = byKey.get(key)
    if (!row) {
      const eng = c.engine ? engineFor(c.engine) : null
      row = {
        from: bare(c.from), fromName: nameOf(c.from),
        to: bare(c.to), toName: nameOf(c.to),
        family: familyOf[c.category] ?? 'Other',
        skill: c.skill, skillName: c.skillName,
        addon: eng ? { id: eng.id, name: eng.name, unlocks: eng.unlocks, license: eng.license } : null,
        verifiedOn: [], verifiedBy: {},
      }
      byKey.set(key, row)
    }
    if (!row.verifiedOn.includes(plat)) row.verifiedOn.push(plat)
    row.verifiedBy[plat] = c.verifiedBy
  }
}
const conversions = [...byKey.values()].sort(
  (a, b) => familyOrder.indexOf(a.family) - familyOrder.indexOf(b.family) || a.from.localeCompare(b.from) || a.to.localeCompare(b.to) || a.skill.localeCompare(b.skill),
)
for (const c of conversions) c.verifiedOn.sort()

const isFile = (e) => e !== '*' && e !== 'folder'
const readable = new Set(conversions.map((c) => c.from).filter(isFile))
const writable = new Set(conversions.map((c) => c.to).filter(isFile))
const builtinReadable = new Set(conversions.filter((c) => !c.addon).map((c) => c.from).filter(isFile))
const pairs = new Set(conversions.filter((c) => c.from !== '*').map((c) => `${c.from}>${c.to}`))

const formats = [...new Set([...readable, ...writable])].sort().map((ext) => ({
  ext,
  name: nameOf(ext),
  families: [...new Set(conversions.filter((c) => c.from === ext || c.to === ext).map((c) => c.family))],
  read: readable.has(ext),
  write: writable.has(ext),
  builtIn: builtinReadable.has(ext),
}))

const doc = {
  schema: 1,
  about:
    'Conversions Asteria has verified: each was run on a real sample file and its output checked by an independent tool on the platforms listed. "addon" is null when the conversion is built in, otherwise the free add-on Asteria offers to download. Generated by scripts/formats/build.mjs from docs/matrix/*.json; do not edit by hand.',
  platforms,
  summary: {
    fileTypesRead: readable.size,
    fileTypesReadBuiltIn: builtinReadable.size,
    fileTypesWritten: writable.size,
    conversionPairs: pairs.size,
    conversions: conversions.length,
  },
  formats,
  conversions,
}
const docJSON = JSON.stringify(doc, null, 2) + '\n'

// ---- README --------------------------------------------------------------
const families = new Map()
for (const c of conversions) {
  const g = families.get(c.family) ?? { from: new Set(), to: new Set(), addons: new Set(), builtin: false }
  if (c.from !== '*') g.from.add(c.from)
  if (isFile(c.to)) g.to.add(c.to)
  if (c.addon) g.addons.add(c.addon.name)
  else g.builtin = true
  families.set(c.family, g)
}
const list = (s) => [...s].sort().join(' ')
const lines = ['| Family | Opens | Saves as | Needs |', '| --- | --- | --- | --- |']
for (const fam of [...familyOrder, 'Other']) {
  const g = families.get(fam)
  if (!g) continue
  const needs = [g.builtin ? 'nothing' : '', ...[...g.addons].sort()].filter(Boolean).join(', ')
  lines.push(`| ${fam} | ${list(g.from)} | ${list(g.to) || 'folders'} | ${needs} |`)
}
const plats = Object.keys(platforms).sort().join(', ')
const block = [
  '<!-- formats:start -->',
  '<!-- Generated by scripts/formats/build.mjs from docs/formats.json. Do not edit by hand. -->',
  '',
  `${pairs.size} conversions between ${readable.size} file types, each tested on a real file with the result checked by a separate tool (${plats}). "nothing" means it's built in; a name means Asteria offers that free add-on the first time you need it. The full list, with what each conversion needs, is in [docs/formats.json](docs/formats.json).`,
  '',
  ...lines,
  '',
  '<!-- formats:end -->',
].join('\n')

const readmePath = join(root, 'README.md')
const before = readFileSync(readmePath, 'utf8')
let after = before.replace(/<!-- formats:start -->[\s\S]*?<!-- formats:end -->/, block)
const marker = (name, n) => {
  after = after.replace(new RegExp(`<!-- formats:${name} -->\\d*<!-- /formats:${name} -->`, 'g'), `<!-- formats:${name} -->${n}<!-- /formats:${name} -->`)
}
marker('count', readable.size)
marker('builtin', builtinReadable.size)
marker('pairs', pairs.size)

const docPath = join(root, 'docs', 'formats.json')
if (check) {
  let current = ''
  try {
    current = readFileSync(docPath, 'utf8')
  } catch {}
  if (current !== docJSON || after !== before) {
    console.error('docs/formats.json or README.md is out of date: run node scripts/formats/build.mjs')
    process.exit(1)
  }
  console.log('docs/formats.json and README.md are up to date')
} else {
  writeFileSync(docPath, docJSON)
  writeFileSync(readmePath, after)
  console.log(`${readable.size} file types read (${builtinReadable.size} built in), ${writable.size} written, ${pairs.size} pairs, ${conversions.length} conversions, platforms: ${plats}`)
}
