#!/usr/bin/env node
// Writes the README's format list and counts from docs/formats.json, the
// format matrix (internal/engine/matrix_test.go): every pair listed there
// was converted from a real fixture and its output checked by an
// independent tool. Nothing else feeds these numbers.
//
//   ASTERIA_MATRIX=1 ASTERIA_MATRIX_OUT=docs/formats.json go test ./internal/engine -run TestMatrix
//   node scripts/formats-readme.mjs            # rewrites README.md between the markers
//   node scripts/formats-readme.mjs --check    # fails if README.md is out of date
//
// Markers: <!-- formats:count -->N<!-- /formats:count -->,
// <!-- formats:builtin -->N<!-- /formats:builtin --> and the block between
// <!-- formats:start --> and <!-- formats:end -->.

import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const report = JSON.parse(readFileSync(join(root, 'docs', 'formats.json'), 'utf8'))
const manifest = JSON.parse(readFileSync(join(root, 'addons', 'manifest.json'), 'utf8'))

// Same families and order as the app (frontend/src/lib/families.ts).
const families = [
  ['convert', 'Images'], ['transform', 'Images'], ['compress', 'Images'], ['adjust', 'Images'],
  ['filter', 'Images'], ['compose', 'Images'], ['sizes', 'Images'],
  ['camera', 'Camera RAW and rare images'], ['vector', 'Vector'], ['lut', 'Color LUTs'],
  ['pdf', 'PDF'], ['document', 'Documents'], ['ebook', 'Ebooks'],
  ['media', 'Audio and video'], ['subtitles', 'Subtitles'],
  ['data', 'Data and config'], ['text', 'Text and encoding'], ['email', 'Email'],
  ['fonts', 'Fonts'], ['maps', 'Maps and GPS'], ['3d', '3D models'],
  ['archive', 'Archives'], ['info', 'Info'],
]
const familyOf = new Map(families)
const order = [...new Set(families.map(([, n]) => n))]

const addonName = (tool) => manifest.engines.find((e) => e.tools.includes(tool))?.name ?? tool
const show = (ext) => (ext === 'folder' ? 'folder' : ext === '*' ? 'any file' : ext.replace(/^\./, ''))
const sortExt = (a, b) => show(a).localeCompare(show(b))

const rows = report.conversions
const readable = new Set(rows.map((r) => r.from).filter((f) => f !== '*' && f !== 'folder'))
const pairs = new Set(rows.filter((r) => r.from !== '*').map((r) => `${r.from}>${r.to}`))
const builtinReadable = new Set(rows.filter((r) => !r.engine).map((r) => r.from).filter((f) => f !== '*' && f !== 'folder'))

const groups = new Map()
for (const r of rows) {
  const fam = familyOf.get(r.category) ?? 'Other'
  const g = groups.get(fam) ?? { from: new Set(), to: new Set(), engines: new Set(), builtin: false, pairs: 0 }
  if (r.from !== '*') g.from.add(r.from)
  if (r.to !== 'folder') g.to.add(r.to)
  if (r.engine) g.engines.add(addonName(r.engine))
  else g.builtin = true
  g.pairs++
  groups.set(fam, g)
}

const lines = [
  '| Family | Reads | Writes | Needs |',
  '| --- | --- | --- | --- |',
]
for (const fam of [...order, 'Other']) {
  const g = groups.get(fam)
  if (!g) continue
  const needs = [g.builtin ? 'nothing' : '', ...[...g.engines].sort()].filter(Boolean).join(', ')
  lines.push(`| ${fam} | ${[...g.from].sort(sortExt).map(show).join(' ')} | ${[...g.to].sort(sortExt).map(show).join(' ') || '(folder)'} | ${needs} |`)
}
const block = [
  '<!-- formats:start -->',
  `<!-- Generated by scripts/formats-readme.mjs from docs/formats.json (${report.platform}, ${report.generated.slice(0, 10)}). Do not edit by hand. -->`,
  '',
  `${pairs.size} verified conversions between ${readable.size} file types. "nothing" means built in; anything else is a free add-on Asteria offers to download when a file needs it.`,
  '',
  ...lines,
  '',
  '<!-- formats:end -->',
].join('\n')

const readmePath = join(root, 'README.md')
const before = readFileSync(readmePath, 'utf8')
let after = before.replace(/<!-- formats:start -->[\s\S]*?<!-- formats:end -->/, block)
after = after.replace(/<!-- formats:count -->\d*<!-- \/formats:count -->/g, `<!-- formats:count -->${readable.size}<!-- /formats:count -->`)
after = after.replace(/<!-- formats:builtin -->\d*<!-- \/formats:builtin -->/g, `<!-- formats:builtin -->${builtinReadable.size}<!-- /formats:builtin -->`)

if (process.argv.includes('--check')) {
  if (after !== before) {
    console.error('README.md format list is out of date: run node scripts/formats-readme.mjs')
    process.exit(1)
  }
  console.log('README.md format list is up to date')
} else {
  writeFileSync(readmePath, after)
  console.log(`${readable.size} file types (${builtinReadable.size} with nothing extra), ${pairs.size} verified conversions`)
}
